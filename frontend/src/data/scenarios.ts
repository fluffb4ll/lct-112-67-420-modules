type IncidentTemplate = Scenario['incident'];

export const OWN_SERVICE_ID = 'OWN';

const OP_112 = { num: '227', arm: '7', name: 'Кузнецова Е. А.' };

const addr = (street: string, house: string, extra: Partial<Address> = {}): Address => ({
  country: 'Россия',
  region: 'Москва',
  city: 'Москва',
  okrug: 'ЮАО',
  district: 'Чертаново Южное',
  street,
  house,
  ...extra,
});

const svc = (name: string, via: 'ARM' | 'VIS' = 'ARM', main = false): ServiceNotification => ({
  serviceId: name,
  name,
  via,
  main,
  history: [],
});

const own = (main = true): ServiceNotification => ({ serviceId: OWN_SERVICE_ID, name: OWN_SERVICE_ID, via: 'ARM', main, history: [] });

function incident(p: {
  card?: string;
  signs: string[];
  finalType: string;
  classifierId?: number;
  address: Address;
  applicant?: Incident['applicant'];
  phone?: string;
  description: string;
  services: ServiceNotification[];
  flags?: Partial<Incident['flags']>;
  source?: Incident['source'];
  sourceName?: string;
}): IncidentTemplate {
  return {
    source: p.source ?? '112',
    sourceName: p.sourceName,
    operator: p.source === 'VIS' ? null : OP_112,
    applicant: p.applicant ?? { name: '', status: '' },
    phones: { aon: p.phone ?? '', provided: p.phone ?? '', onSite: '' },
    channel: 'МТС',
    address: p.address,
    descriptions: [{ at: '', author: p.source === 'VIS' ? p.sourceName ?? 'ВИС' : `${OP_112.num} ${OP_112.name}`, text: p.description }],
    type: { card: p.card ?? 'Аварии и происшествия в городском хозяйстве', signs: p.signs, finalType: p.finalType, classifierId: p.classifierId },
    flags: { victims: false, ambulanceRefused: false, blocked: false, chs: false, chp: false, important: false, ...p.flags },
    cardStatus: 'Зарегистрирована',
    services: p.services,
    otrabotki: [],
    linkedIds: [],
  };
}

