import { describe, expect, it } from 'vitest';
import { matchGroups } from './text';

// Случаи один в один с ai/tests/test_bridge_rules_fuzzy.py: локальная и серверная проверка доклада совпадают.
// реальный ответ faster-whisper на доклад «…застревание в лифте…»
const STT_REPORT = 'Докладываю Днепропетровская улица, дом 19, состревание в листе, ребенок без взрослых';
const GROUPS = [['днепро', '19'], ['застре']];

describe('matchGroups — доклад из распознавания речи (как в ai)', () => {
  it('засчитывает корень, искажённый распознаванием', () => {
    expect(matchGroups(STT_REPORT, GROUPS, { fuzzy: true })).toEqual({ hit: 2, missing: [] });
  });

  it('без fuzzy сверяет строго: комментарии набраны руками', () => {
    expect(matchGroups(STT_REPORT, GROUPS).missing).toEqual([['застре']]);
  });

  it.each([
    ['состревание в лифте', 'застре'], // з/с и безударная о/а
    ['застриване в лифте', 'застре'], // е/и
    ['кирафоградская 22', 'кировоградск'], // одна правка в длинном корне (в/ф, о/а)
    ['кировградская 22', 'кировоградск'], // пропуск буквы в длинном корне
    ['Застрял', 'застре'], // формы глагола: я/е после свёртки
    ['застряли между этажами', 'застре'],
    ['в листе', 'лифт'], // созвучие, которое STT выдаёт стабильно
    ['застревание в листе', 'лифт'],
  ])('«%s» содержит «%s»', (text, stem) => {
    expect(matchGroups(text, [[stem]], { fuzzy: true }).hit).toBe(1);
  });

  it.each([
    ['приехал застройщик', 'застре'], // другое слово с похожим началом
    ['нас заставили ждать', 'застре'],
    ['раздали листовки', 'лифт'], // у созвучия — только падежное окончание
    ['упал листок', 'лифт'],
    ['жёлтые листья', 'лифт'],
    ['листать журнал', 'лифт'],
    ['лифчик', 'лифт'], // короткий корень без созвучия — только точно
    ['застрахован', 'застре'],
    ['дом 91', '19'], // числа — только точно
    ['ушли домой', 'домов'], // 5 букв: правка не прощается
    ['кировская 22', 'кировоградск'],
  ])('«%s» не содержит «%s»', (text, stem) => {
    expect(matchGroups(text, [[stem]], { fuzzy: true }).hit).toBe(0);
  });

  it('случай из UI: «Застрял» в докладе засчитан', () => {
    // разбор писал «В докладе не прозвучало: «застре…»» на «Застрял»
    const groups = [['днепропетровск', '19'], ['застре'], ['лифт']];
    expect(matchGroups('Днепропетровская 19, застрял ребёнок, состревание в листе', groups, { fuzzy: true })).toEqual({ hit: 3, missing: [] });
    expect(matchGroups('Застрял', [['застре']], { fuzzy: true })).toEqual({ hit: 1, missing: [] });
  });
});

describe('matchGroups — дополнительно во фронте', () => {
  it.each([
    ['в лифте', 'лифт'],
    ['застряли в листах', 'лифт'],
    ['доложил о листе', 'лифт'],
  ])('«%s» содержит «%s»', (text, stem) => {
    expect(matchGroups(text, [[stem]], { fuzzy: true }).hit).toBe(1);
  });

  it('созвучия — только для доклада из STT, набранный текст строго', () => {
    expect(matchGroups('в листе', [['лифт']]).hit).toBe(0);
  });

  it('многословный корень ищется подстрокой, как раньше', () => {
    expect(matchGroups('это не наш адрес', [['не наш']], { fuzzy: true }).hit).toBe(1);
  });
});
